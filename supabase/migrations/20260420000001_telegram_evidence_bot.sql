-- ── 2. telegram_chat_bindings ────────────────────────────────────────────────
--
-- Persistent mapping of Telegram chat_id → driver_id within a tenant.
-- Re-binding is supported without DELETE: unbound_at_utc is stamped on the
-- old row, and a new row is inserted. Partial unique indexes enforce that
-- only one active binding exists per chat AND per driver simultaneously.

CREATE TABLE IF NOT EXISTS public.telegram_chat_bindings (
  id                  UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id     UUID        NOT NULL,
  driver_id           UUID        NOT NULL REFERENCES public.drivers(id),

  -- BIGINT: Telegram chat IDs for groups/supergroups are large negatives.
  chat_id             BIGINT      NOT NULL,

  bound_at_utc        TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  -- NULL = active; stamped when re-binding replaces this entry.
  unbound_at_utc      TIMESTAMPTZ,

  -- Forensic link: which token established this binding.
  binding_token_id    UUID        NOT NULL
    REFERENCES public.telegram_binding_tokens(id)
);

-- One active binding per chat_id (prevents two drivers sharing a chat).
CREATE UNIQUE INDEX IF NOT EXISTS idx_tcb_chat_active
  ON public.telegram_chat_bindings (chat_id)
  WHERE unbound_at_utc IS NULL;

-- One active binding per driver (single-chat policy).
CREATE UNIQUE INDEX IF NOT EXISTS idx_tcb_driver_active
  ON public.telegram_chat_bindings (driver_id)
  WHERE unbound_at_utc IS NULL;

CREATE INDEX IF NOT EXISTS idx_tcb_org_driver
  ON public.telegram_chat_bindings (organization_id, driver_id);

CREATE INDEX IF NOT EXISTS idx_tcb_chat_id
  ON public.telegram_chat_bindings (chat_id);

-- Immutability: identity fields frozen; unbound_at_utc may only transition NULL → timestamp once.
CREATE OR REPLACE FUNCTION public.prevent_tcb_immutable_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
