-- ── 4. RPC: consume_telegram_binding_token ───────────────────────────────────
--
-- Atomic: validates token → invalidates old bindings → inserts new binding.
-- Called by the webhook Edge Function with service_role client (no JWT).
-- SECURITY DEFINER bypasses RLS; caller trust comes from TELEGRAM_WEBHOOK_SECRET.

CREATE OR REPLACE FUNCTION public.consume_telegram_binding_token(
  p_code     TEXT,
  p_chat_id  BIGINT
)
RETURNS TABLE(driver_id UUID, organization_id UUID)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_token public.telegram_binding_tokens%ROWTYPE;
BEGIN
  -- 1. Load and lock the token row (serializes concurrent attempts).
  SELECT * INTO v_token
    FROM public.telegram_binding_tokens
   WHERE code = p_code
     FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Token not found.'
      USING ERRCODE = 'no_data_found';
  END IF;

  -- 2. Validate: not expired.
  IF NOW() > v_token.expires_at_utc THEN
    RAISE EXCEPTION 'Token has expired.'
      USING ERRCODE = 'check_violation';
  END IF;

  -- 3. Validate: not already used.
  IF v_token.used_at_utc IS NOT NULL THEN
    RAISE EXCEPTION 'Token has already been used.'
      USING ERRCODE = 'unique_violation';
  END IF;

  -- 4. Invalidate existing active binding for this chat_id (re-bind flow).
  UPDATE public.telegram_chat_bindings
     SET unbound_at_utc = NOW()
   WHERE telegram_chat_bindings.chat_id = p_chat_id
     AND telegram_chat_bindings.unbound_at_utc IS NULL;

  -- 5. Invalidate existing active binding for this driver (single-chat policy).
  UPDATE public.telegram_chat_bindings
     SET unbound_at_utc = NOW()
   WHERE telegram_chat_bindings.driver_id = v_token.driver_id
     AND telegram_chat_bindings.unbound_at_utc IS NULL;

  -- 6. Insert new active binding.
  INSERT INTO public.telegram_chat_bindings (
    organization_id, driver_id, chat_id, bound_at_utc, binding_token_id
  ) VALUES (
    v_token.organization_id, v_token.driver_id, p_chat_id, NOW(), v_token.id
  );

  -- 7. Stamp token as used.
  UPDATE public.telegram_binding_tokens
     SET used_at_utc = NOW()
   WHERE id = v_token.id;

  RETURN QUERY SELECT v_token.driver_id, v_token.organization_id;
END;
$$;

REVOKE ALL ON FUNCTION public.consume_telegram_binding_token(TEXT, BIGINT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.consume_telegram_binding_token(TEXT, BIGINT)
  TO authenticated;

-- ── 5. Function: check_telegram_rate_limit ───────────────────────────────────
--
-- DB-backed rate limiter: counts committed uploads in the last 60 seconds
-- for a given chat_id. Returns TRUE = allowed, FALSE = blocked.
-- Leverages the existing telegram_evidence_uploads table — no extra table needed.
-- Threshold: 10 uploads per chat per 60s (stops DoS, allows burst from drivers).

CREATE OR REPLACE FUNCTION public.check_telegram_rate_limit(p_chat_id BIGINT)
RETURNS BOOLEAN
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT COUNT(*) < 10
  FROM public.telegram_evidence_uploads
  WHERE chat_id = p_chat_id
    AND uploaded_at_utc > NOW() - INTERVAL '60 seconds';
$$;

REVOKE ALL ON FUNCTION public.check_telegram_rate_limit(BIGINT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.check_telegram_rate_limit(BIGINT) TO authenticated;

