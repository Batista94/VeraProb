-- ── 1. telegram_binding_tokens ───────────────────────────────────────────────
--
-- Short-lived 8-char code generated by operator; consumed by Telegram bot
-- to bind a driver's chat_id to their profile.
--
-- Alphabet: ABCDEFGHJKMNPQRSTUVWXYZ23456789 (32 unambiguous chars, 40 bits).
-- Ambiguous chars excluded: 0/O, 1/I/L.
-- Low entropy compensated by 15-minute TTL.

CREATE TABLE IF NOT EXISTS public.telegram_binding_tokens (
  id                  UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id     UUID        NOT NULL,
  driver_id           UUID        NOT NULL REFERENCES public.drivers(id),
  created_by_user_id  UUID        NOT NULL,

  code                TEXT        NOT NULL UNIQUE
    CONSTRAINT chk_tbt_code_format
      CHECK (code ~ '^[ABCDEFGHJKMNPQRSTUVWXYZ23456789]{8}$'),

  expires_at_utc      TIMESTAMPTZ NOT NULL
    CONSTRAINT chk_tbt_expires_window
      CHECK (
        expires_at_utc > created_at_utc
        AND expires_at_utc <= created_at_utc + INTERVAL '15 minutes'
      ),

  -- Stamped once (NULL → timestamp) when bot consumes the code. Never reset.
  used_at_utc         TIMESTAMPTZ,

  created_at_utc      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_tbt_code
  ON public.telegram_binding_tokens (code);

CREATE INDEX IF NOT EXISTS idx_tbt_org_driver
  ON public.telegram_binding_tokens (organization_id, driver_id);

CREATE INDEX IF NOT EXISTS idx_tbt_expires
  ON public.telegram_binding_tokens (expires_at_utc)
  WHERE used_at_utc IS NULL;

-- Immutability: all fields frozen; used_at_utc may only transition NULL → timestamp once.
CREATE OR REPLACE FUNCTION public.prevent_tbt_immutable_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.used_at_utc IS NOT NULL AND
     NEW.used_at_utc IS DISTINCT FROM OLD.used_at_utc
  THEN
    RAISE EXCEPTION
      'telegram_binding_tokens: used_at_utc already stamped (INV-7). id: %', OLD.id
    USING ERRCODE = 'restrict_violation';
  END IF;

  IF NEW.organization_id     IS DISTINCT FROM OLD.organization_id     OR
     NEW.driver_id           IS DISTINCT FROM OLD.driver_id           OR
     NEW.created_by_user_id  IS DISTINCT FROM OLD.created_by_user_id  OR
     NEW.code                IS DISTINCT FROM OLD.code                OR
     NEW.expires_at_utc      IS DISTINCT FROM OLD.expires_at_utc      OR
     NEW.created_at_utc      IS DISTINCT FROM OLD.created_at_utc
  THEN
    RAISE EXCEPTION
      'telegram_binding_tokens: immutable field mutation (INV-7). id: %', OLD.id
    USING ERRCODE = 'restrict_violation';
  END IF;
  RETURN NEW;
END;
$$;

