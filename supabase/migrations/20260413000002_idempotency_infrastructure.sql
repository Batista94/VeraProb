-- ── 7. Atomic transactional RPC: register → execute → complete ──────────────
--
-- This function provides atomic idempotency for command execution.
-- It is called by the Dart application layer with a command identifier,
-- and wraps the entire check-register-execute-commit cycle in a single
-- database transaction.
--
-- FLOW:
--   1. Check if key exists with status = 'completed' → return cached response.
--   2. Check if key exists with status = 'processing' → raise exception (duplicate in-flight).
--   3. INSERT key as 'processing' (ON CONFLICT DO NOTHING for race condition safety).
--   4. If insert succeeded (another thread didn't beat us):
--      a. Caller executes business logic (outside this function).
--      b. Caller calls complete_idempotency_key() to mark as completed.
--   5. If insert failed (key already existed as 'processing'):
--      a. Raise exception — caller should abort.
--
-- NOTE: This function does NOT execute business logic itself. It only manages
-- the idempotency key state. The caller (Dart handler) is responsible for:
--   - Calling this function BEFORE business logic.
--   - Calling complete_idempotency_key() AFTER business logic succeeds.
--   - Calling fail_idempotency_key() if business logic fails.
--
-- This separation is intentional: business logic may involve multiple tables
-- and domain events that cannot be encapsulated in a single SQL function.

CREATE OR REPLACE FUNCTION public.try_acquire_idempotency_key(
  p_id                    TEXT,
  p_user_id               UUID,
  p_command_path          TEXT,
  p_organization_id       UUID,
  p_stale_threshold_min   INT DEFAULT 5
)
RETURNS JSONB
LANGUAGE plpgsql
AS $$
DECLARE
  v_existing RECORD;
  v_inserted BOOLEAN;
  v_stale_threshold INTERVAL;
BEGIN
  -- Step 1: Check if key already exists.
  -- Read the per-key stale_threshold_minutes to avoid reclaiming heavy commands prematurely.
  SELECT status, response_code, response_body, created_at_utc, completed_at_utc,
         COALESCE(stale_threshold_minutes, 5) AS stale_threshold_minutes
    INTO v_existing
    FROM public.idempotency_keys
   WHERE id = p_id AND user_id = p_user_id
   LIMIT 1;

  -- Key found.
  IF FOUND THEN
    IF v_existing.status = 'completed' THEN
      -- Short-circuit: return cached response.
      RETURN jsonb_build_object(
        'hit', true,
        'status', 'completed',
        'response_code', v_existing.response_code,
        'response_body', v_existing.response_body,
        'completed_at_utc', v_existing.completed_at_utc
      );
    ELSIF v_existing.status = 'processing' THEN
      -- ── Stale Detection: Zombie Key Recovery ──────────────────────────
      -- Use the per-key threshold (default 5 min). Heavy commands set 30+.
      v_stale_threshold := (v_existing.stale_threshold_minutes || ' minutes')::INTERVAL;

      IF NOW() - v_existing.created_at_utc > v_stale_threshold THEN
        UPDATE public.idempotency_keys
           SET status = 'processing',
               response_code = NULL,
               response_body = NULL,
               completed_at_utc = NULL,
               created_at_utc = NOW()
         WHERE id = p_id AND user_id = p_user_id AND status = 'processing';

        RETURN jsonb_build_object(
          'hit', false,
          'status', 'processing',
          'acquired', true,
          'reclaimed_from_stale', true
        );
      END IF;

      -- Not stale yet — another thread is genuinely processing.
      RAISE EXCEPTION
        'IdempotencyProcessingException: Command is already being processed. '
        'key: %, command: %, user_id: %',
        p_id, p_command_path, p_user_id
      USING ERRCODE = 'unique_violation',
            DETAIL = 'Another request is processing this command. Retry or poll status.';
    ELSIF v_existing.status = 'error' THEN
      -- Previous attempt failed — allow retry by updating to 'processing'.
      UPDATE public.idempotency_keys
         SET status = 'processing',
             response_code = NULL,
             response_body = NULL,
             completed_at_utc = NULL
       WHERE id = p_id AND user_id = p_user_id AND status = 'error';
      RETURN jsonb_build_object(
        'hit', false,
        'status', 'processing',
        'acquired', true
      );
    END IF;
  END IF;

  -- Step 2: Key not found or was 'error' — try to register as 'processing'.
  INSERT INTO public.idempotency_keys (id, user_id, command_path, organization_id, status, created_at_utc)
  VALUES (p_id, p_user_id, p_command_path, p_organization_id, 'processing', NOW())
  ON CONFLICT (id, user_id) DO NOTHING;

  GET DIAGNOSTICS v_inserted = ROW_COUNT;

  IF v_inserted = 0 THEN
    -- Race condition: another thread inserted the key between our check and insert.
    -- Re-check the status and per-key threshold.
    SELECT status, created_at_utc, COALESCE(stale_threshold_minutes, 5) AS stale_threshold_minutes
      INTO v_existing
      FROM public.idempotency_keys
     WHERE id = p_id AND user_id = p_user_id
     LIMIT 1;

    IF FOUND AND v_existing.status = 'completed' THEN
      RETURN jsonb_build_object(
        'hit', true,
        'status', 'completed',
        'response_code', v_existing.response_code,
        'response_body', v_existing.response_body,
        'completed_at_utc', v_existing.completed_at_utc
      );
    ELSIF FOUND AND v_existing.status = 'processing' THEN
      -- Stale detection for race condition path: use per-key threshold.
      v_stale_threshold := (v_existing.stale_threshold_minutes || ' minutes')::INTERVAL;
      IF NOW() - v_existing.created_at_utc > v_stale_threshold THEN
        UPDATE public.idempotency_keys
           SET status = 'processing',
               response_code = NULL,
               response_body = NULL,
               completed_at_utc = NULL,
               created_at_utc = NOW()
         WHERE id = p_id AND user_id = p_user_id AND status = 'processing';

        RETURN jsonb_build_object(
          'hit', false,
          'status', 'processing',
          'acquired', true,
          'reclaimed_from_stale', true
        );
      END IF;
    END IF;

    RAISE EXCEPTION
      'IdempotencyProcessingException: Command is already being processed (race condition). '
      'key: %, command: %, user_id: %',
      p_id, p_command_path, p_user_id
    USING ERRCODE = 'unique_violation',
          DETAIL = 'Race condition detected. Another request won the insert race.';
  END IF;

  -- Step 3: Key successfully registered as 'processing'.
  RETURN jsonb_build_object(
    'hit', false,
    'status', 'processing',
    'acquired', true
  );
END;
$$;

-- ── 8. Complete idempotency key (mark as completed with response body) ───────

CREATE OR REPLACE FUNCTION public.complete_idempotency_key(
  p_id            TEXT,
  p_user_id       UUID,
  p_response_code INT,
  p_response_body JSONB
)
RETURNS VOID
LANGUAGE plpgsql
AS $$
BEGIN
  UPDATE public.idempotency_keys
     SET status = 'completed',
         response_code = p_response_code,
         response_body = p_response_body,
         completed_at_utc = NOW()
   WHERE id = p_id
     AND user_id = p_user_id
     AND status = 'processing';

  -- If no rows updated, the key may have been rolled back or already completed.
  -- This is a no-op — the caller should log a warning.
  IF NOT FOUND THEN
    RAISE WARNING 'complete_idempotency_key: no processing key found for id=%, user_id=%', p_id, p_user_id;
  END IF;
END;
$$;

-- ── 9. Fail idempotency key (mark as error) ─────────────────────────────────

CREATE OR REPLACE FUNCTION public.fail_idempotency_key(
  p_id            TEXT,
  p_user_id       UUID,
  p_response_code INT
)
RETURNS VOID
LANGUAGE plpgsql
AS $$
BEGIN
  UPDATE public.idempotency_keys
     SET status = 'error',
         response_code = p_response_code,
         completed_at_utc = NOW()
   WHERE id = p_id
     AND user_id = p_user_id
     AND status = 'processing';

  IF NOT FOUND THEN
    RAISE WARNING 'fail_idempotency_key: no processing key found for id=%, user_id=%', p_id, p_user_id;
  END IF;
END;
$$;

