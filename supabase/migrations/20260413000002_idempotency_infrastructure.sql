-- =============================================================================
-- Migration: 20260413000002 — Idempotency Keys Infrastructure (INV-33)
--
-- PURPOSE:
--   Implements command-level idempotency to guarantee that duplicate requests
--   (double-clicks, network retries, infrastructure failures) never produce
--   duplicate side-effects.
--
-- DESIGN:
--   - Idempotency keys are stored in Postgres (NOT in-memory) to survive
--     process restarts and horizontal scaling.
--   - Keys are scoped to (id, user_id) — each user has independent idempotency.
--   - The key is registered BEFORE business logic executes, then updated to
--     'completed' WITH the response body AFTER persistence succeeds.
--   - All three steps (check key → execute → update key) occur within a SINGLE
--     database transaction. If business logic fails, the key registration is
--     rolled back atomically — no orphaned 'processing' keys.
--
-- INVARIANTS:
--   INV-1:  organization_id filters all queries (tenant isolation).
--   INV-6:  All timestamps are UTC.
--   INV-9:  response_body stored as canonical JSON for replay parity.
--   INV-26: Error parity — 404 for 'not found' AND 'other org' (handled in app layer).
--   INV-30: SupabaseClient injected via constructor (DI Total).
--   INV-32: response_body includes the updated version (V+2) for optimistic locking.
--   INV-33: Idempotency keys — new invariant introduced by this migration.
--
-- INV-33 RULES:
--   (a) Every mutating command MUST carry an idempotencyKey generated by the client.
--   (b) The key is CHECKed before any business logic executes.
--   (c) If key status = 'completed' → return cached response_body (short-circuit).
--   (d) If key status = 'processing' → reject with IdempotencyProcessingException
--       (another thread is already handling this request).
--   (e) If key is null → INSERT as 'processing', execute business logic, then
--       UPDATE to 'completed' with response_body — all within one transaction.
--   (f) If the transaction rolls back, the key registration is also rolled back.
-- =============================================================================

-- ── 1. idempotency_keys table ────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.idempotency_keys (
  id              TEXT        NOT NULL,
  user_id         UUID        NOT NULL
    REFERENCES auth.users(id) ON DELETE CASCADE,
  command_path    TEXT        NOT NULL,
  organization_id UUID        NOT NULL,
  status          TEXT        NOT NULL
    CHECK (status IN ('processing', 'completed', 'error')),
  response_code   INT,
  response_body   JSONB,
  created_at_utc  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  completed_at_utc TIMESTAMPTZ,

  -- Per-key stale threshold (minutes). Heavy commands (e.g., monthly audit)
  -- can set 30+ to prevent premature reclamation. Default: 5.
  stale_threshold_minutes INT NOT NULL DEFAULT 5,

  -- Composite primary key: (id, user_id) ensures per-user idempotency.
  PRIMARY KEY (id, user_id)
);

-- Index for fast lookup by user + status (cleanup query).
CREATE INDEX IF NOT EXISTS idx_idempotency_keys_user_status
  ON public.idempotency_keys (user_id, status);

-- Index for cleanup: find old completed/error keys by age.
CREATE INDEX IF NOT EXISTS idx_idempotency_keys_created_at
  ON public.idempotency_keys (created_at_utc);

-- Index for organization-scoped queries (audit/debug).
CREATE INDEX IF NOT EXISTS idx_idempotency_keys_org
  ON public.idempotency_keys (organization_id);

-- ── 2. RLS policies ─────────────────────────────────────────────────────────

ALTER TABLE public.idempotency_keys ENABLE ROW LEVEL SECURITY;

-- Users can only see their own idempotency keys.
DROP POLICY IF EXISTS idempotency_keys_select_own
  ON public.idempotency_keys;
CREATE POLICY idempotency_keys_select_own
  ON public.idempotency_keys
  FOR SELECT
  USING (
    user_id = auth.uid()
  );

-- Users can only insert their own keys (status = 'processing' on creation).
DROP POLICY IF EXISTS idempotency_keys_insert_own
  ON public.idempotency_keys;
CREATE POLICY idempotency_keys_insert_own
  ON public.idempotency_keys
  FOR INSERT
  WITH CHECK (
    user_id = auth.uid()
    AND status = 'processing'
  );

-- Users can only update their own keys (processing → completed/error).
DROP POLICY IF EXISTS idempotency_keys_update_own
  ON public.idempotency_keys;
CREATE POLICY idempotency_keys_update_own
  ON public.idempotency_keys
  FOR UPDATE
  USING (user_id = auth.uid())
  WITH CHECK (
    user_id = auth.uid()
    AND status IN ('completed', 'error')
  );

-- Service role bypass (for server-side command handlers).
DROP POLICY IF EXISTS idempotency_keys_service_all
  ON public.idempotency_keys;
CREATE POLICY idempotency_keys_service_all
  ON public.idempotency_keys
  FOR ALL
  USING (true)
  WITH CHECK (true);

-- ── 3. Immutable fields after creation ───────────────────────────────────────
--    Only status, response_code, response_body, and completed_at_utc can change.
--    id, user_id, command_path, organization_id, created_at_utc are frozen.

CREATE OR REPLACE FUNCTION public.prevent_idempotency_key_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.id                IS DISTINCT FROM OLD.id                OR
     NEW.user_id           IS DISTINCT FROM OLD.user_id           OR
     NEW.command_path      IS DISTINCT FROM OLD.command_path      OR
     NEW.organization_id   IS DISTINCT FROM OLD.organization_id   OR
     NEW.created_at_utc    IS DISTINCT FROM OLD.created_at_utc
  THEN
    RAISE EXCEPTION
      'idempotency_keys: immutable field mutation. id: %, user_id: %',
      OLD.id, OLD.user_id
    USING ERRCODE = 'restrict_violation';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_idempotency_keys_no_mutation
  ON public.idempotency_keys;
CREATE TRIGGER trg_idempotency_keys_no_mutation
  BEFORE UPDATE ON public.idempotency_keys
  FOR EACH ROW EXECUTE FUNCTION public.prevent_idempotency_key_mutation();

-- ── 4. Cleanup function ─────────────────────────────────────────────────────
--    Removes completed/error keys older than N days to prevent table bloat.
--    This is a maintenance function — should be called by a cron job or
--    Supabase scheduled job (e.g., daily).

CREATE OR REPLACE FUNCTION public.cleanup_expired_idempotency(
  days_threshold INT DEFAULT 30
)
RETURNS INT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_cutoff   TIMESTAMPTZ;
  v_deleted  INT;
BEGIN
  v_cutoff := NOW() - (days_threshold || ' days')::INTERVAL;

  -- Delete old completed/error keys.
  -- 'processing' keys are NEVER deleted — they indicate an in-flight operation
  -- or a rolled-back transaction (which should be rare and investigated).
  DELETE
    FROM public.idempotency_keys
   WHERE status IN ('completed', 'error')
     AND created_at_utc < v_cutoff;

  GET DIAGNOSTICS v_deleted = ROW_COUNT;

  RETURN v_deleted;
END;
$$;

-- ── 5. Prevent deletion of 'processing' keys (safety net) ───────────────────

CREATE OR REPLACE FUNCTION public.prevent_idempotency_processing_delete()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF OLD.status = 'processing' THEN
    RAISE EXCEPTION
      'idempotency_keys: cannot DELETE processing keys. id: %, user_id: %. '
      'This may indicate a rollback or orphaned transaction.',
      OLD.id, OLD.user_id
    USING ERRCODE = 'restrict_violation';
  END IF;
  RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS trg_idempotency_no_delete_processing
  ON public.idempotency_keys;
CREATE TRIGGER trg_idempotency_no_delete_processing
  BEFORE DELETE ON public.idempotency_keys
  FOR EACH ROW EXECUTE FUNCTION public.prevent_idempotency_processing_delete();

